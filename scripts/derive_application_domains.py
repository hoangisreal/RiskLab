"""Derive ``configs/application_domains.yaml`` from the ingested application_train Parquet.

One-off dev script. It reads only the distinct values of the VARCHAR (categorical) columns, never
TARGET. Review the output, then commit it; the file is the reviewed contract, not regenerated by
the pipeline.

Usage: uv run python scripts/derive_application_domains.py [--config-dir DIR] [--out PATH]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

from risklab.config import load_data_config, load_raw_schema, resolve_config_dir
from risklab.data.duckdb_utils import duckdb_connect
from risklab.data.ingest import quote_ident

TABLE = "application_train"
HEADER = """\
# Allowed values for every VARCHAR column of application_train (validation contract).
# Derived once by scripts/derive_application_domains.py from the real Parquet, then reviewed.
# NULL is always allowed here; null rates are reported separately by `risklab validate`.
# 'XNA' ("not applicable") is listed where it occurs in the raw data.
# Categories unseen at serving time are handled by the API contract (MASTER_PLAN Section 10),
# not by this file.
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config-dir", default=None)
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args()
    cfg_dir = resolve_config_dir(args.config_dir)
    cfg = load_data_config(cfg_dir)
    schema = load_raw_schema(cfg_dir, data_cfg=cfg)
    parquet = cfg.parquet_dir / f"{TABLE}.parquet"

    con = duckdb_connect(cfg.duckdb)
    domains: dict[str, list[str]] = {}
    for col in schema.columns(TABLE):
        if col.type != "VARCHAR":
            continue
        q = quote_ident(col.name)
        rows = con.execute(
            f"SELECT DISTINCT {q} FROM read_parquet(?) WHERE {q} IS NOT NULL ORDER BY 1",
            [str(parquet)],
        ).fetchall()
        domains[col.name] = [r[0] for r in rows]
    out = args.out or cfg_dir / "application_domains.yaml"
    body = yaml.safe_dump({"domains": domains}, sort_keys=False, allow_unicode=True, width=100)
    out.write_text(HEADER + body, encoding="utf-8")
    print(f"wrote {out} ({len(domains)} columns, {sum(map(len, domains.values()))} values)")


if __name__ == "__main__":
    main()
